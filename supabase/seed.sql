-- -----------------------------------------------------------------------------
-- Токен админа
-- -----------------------------------------------------------------------------
-- Создаётся один раз. При повторном запуске остаётся прежним — ссылка не протухнет.
insert into public.access_tokens (token, role, doctor_id, label)
select encode(extensions.gen_random_bytes(12), 'hex'), 'admin', null, 'Организатор'
 where not exists (select 1 from public.access_tokens where role = 'admin');

-- -----------------------------------------------------------------------------
-- Доктора
-- -----------------------------------------------------------------------------
-- Здесь СОЗНАТЕЛЬНО пусто.
--
-- Ни докторов, ни тем столов на момент написания неизвестно — экспертов ещё ищут.
-- Придумывать заглушки со специализациями значило бы зафиксировать выдумку
-- в схеме и в QR-кодах столов.
--
-- Доктора заводятся в админке по мере того, как находятся: admin.html?t=<токен>,
-- вкладка «Доктора» -> «+ Добавить». Токен доступа к личному кабинету создаётся
-- автоматически, забирается кнопкой «Ссылка».
--
-- Идентификатор — фамилия латиницей (ivanov, petrov). Он же имя файла фото:
-- assets/doctors/<id>.jpg. После создания не меняется.
--
-- QR один на всё мероприятие и ведёт на витрину докторов, поэтому от
-- идентификаторов не зависит: заменили доктора — перепечатали только имя
-- на табличке, ссылка осталась прежней.
--
-- Когда состав утвердится, полезно вписать его сюда для воспроизводимости.
-- Шаблон:
--
-- insert into public.doctors (id, name, role, specialty, bio, table_no, sort, active)
-- values ('ivanov', 'Иван Иванов', 'Должность, команда',
--         'С чем помогает', 'Опыт, 2-4 предложения.', 1, 10, true)
-- on conflict (id) do nothing;   -- do nothing, чтобы не затирать правки из админки

-- -----------------------------------------------------------------------------
-- Токены докторов — на случай, если доктора заводились SQL-ом выше
-- -----------------------------------------------------------------------------
insert into public.access_tokens (token, role, doctor_id, label)
select encode(extensions.gen_random_bytes(12), 'hex'), 'doctor', d.id, d.name
  from public.doctors d
 where not exists (
   select 1 from public.access_tokens t where t.doctor_id = d.id and t.role = 'doctor'
 );

-- -----------------------------------------------------------------------------
-- Ссылки для раздачи. Скопировать вывод.
-- -----------------------------------------------------------------------------
select
  t.role,
  coalesce(d.name, 'Организатор') as who,
  case t.role
    when 'admin'  then 'admin.html?t='  || t.token
    else               'doctor.html?doc=' || t.doctor_id || '&t=' || t.token
  end as link
from public.access_tokens t
left join public.doctors d on d.id = t.doctor_id
order by t.role, d.sort;
